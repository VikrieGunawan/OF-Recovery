/**
 * Theme strategy requested for OF Recovery:
 *  - Android 12+ (S) : Material You dynamic color sampled from the wallpaper.
 *  - Older devices   : the hand-tuned Fox Orange palette above.
 * Users can force the Fox palette at any time from Settings (dynamic off).
 */
@Composable
fun FoxTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        darkTheme -> DarkFoxColors
        else -> LightFoxColors
    }
    MaterialTheme(
        colorScheme = colorScheme,
        typography = FoxTypography,
        shapes = FoxShapes,
        content = content
    )
}
